import Foundation
import Testing
@testable import AllSetCore

/// The numbers README.md and CONTENT.md quote come from the code, here, and
/// nowhere else. The docs hold them between `<!-- counts -->` markers; this
/// fails when they disagree. To write the current numbers into both files:
///
///     UPDATE_COUNTS=1 swift test --filter ContentCountsTests
@Suite struct ContentCountsTests {
    static var counts: [(String, Int)] {
        [
            ("widget kinds", WidgetKind.allCases.count),
            ("widgets in the gallery", WidgetCatalog.entries.count),
            ("widgets from themes", ThemeWidgetCatalog.all.count),
            ("themes (whole desktops)", ThemeLibrary.all.count),
            ("built-in live wallpapers", BuiltInWallpaper.all.count),
            ("design themes", DesignTheme.all.count),
            ("generative artworks (styles × palettes)", ArtStyle.allCases.count * ArtPalette.allCases.count),
            ("extras", Extra.allCases.count),
        ]
    }

    static var block: String {
        (["<!-- counts: generated by Tests/AllSetCoreTests/ContentCountsTests.swift; don't edit by hand -->"]
            + counts.map { "- \($0.1) \($0.0)" }
            + ["<!-- /counts -->"]).joined(separator: "\n")
    }

    static let pattern = #"(?s)<!-- counts:.*?<!-- /counts -->"#

    @Test(arguments: ["README.md", "CONTENT.md"])
    func docsQuoteTheCode(_ name: String) throws {
        let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
        let file = root.appendingPathComponent(name)
        var text = try String(contentsOf: file, encoding: .utf8)
        guard let range = text.range(of: Self.pattern, options: .regularExpression) else {
            Issue.record("\(name) has no <!-- counts --> block")
            return
        }
        if ProcessInfo.processInfo.environment["UPDATE_COUNTS"] == "1" {
            text.replaceSubrange(range, with: Self.block)
            try text.write(to: file, atomically: true, encoding: .utf8)
            return
        }
        #expect(String(text[range]) == Self.block, "\(name)'s counts are out of date: UPDATE_COUNTS=1 swift test --filter ContentCountsTests")
    }
}
